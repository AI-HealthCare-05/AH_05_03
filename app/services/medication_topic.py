"""의약품 질문인지 판별하는 키워드의 단일 진실 원천.

`health_assistant_boundary.py`(fast-path 판정)와 `health_assistant.py`(실제
`search_medication_info` 도구 연결)가 예전에는 이 판단을 각자 따로 복사해
갖고 있었다. 그런데 두 목록이 서로 달랐다 — boundary 쪽은 "약"을 부분
문자열로만 봤고(예: "제약회사"의 "약"도 걸림), 여기 쪽은 표준화된 정규식
(홀로 쓰인 "약"만, 조사까지만 허용)을 썼다. 그 결과 "제약회사 효능 알려줘"
같은 질문은 boundary가 medication 근거를 필수라고 판정하는데 실제 도구는
안 붙어서, 근거를 영원히 못 채우고 차단됐다. 여기 하나로 모은다.
"""

from __future__ import annotations

import re

# `약` 한 글자를 부분 문자열로 찾으면 약간·약속·요약·계약·예약·절약·만약·약해요가
# 전부 의약품 질문이 된다. 홀로 쓰인 `약`(뒤에 조사까지만)에만 맞춘다 —
# "이 약 효능이 뭐야", "약을 먹어도 되나요". 혈압약·감기약 같은 합성어는 아래
# 키워드 목록이 따로 잡으므로 잃는 것이 없다.
STANDALONE_MEDICINE_WORD = re.compile(r"(?<![가-힣])약[은는이가을를도만에의과와로]?(?![가-힣])")

MEDICATION_KEYWORDS = (
    "약품",
    "약물",
    "복약",
    "복용",
    "부작용",
    "병용",
    "같이 먹",
    "같이먹",
    "함께 먹",
    "함께먹",
    "먹어도 돼",
    "먹어도돼",
    "먹어도 되",
    "먹어도되",
    "복용해도 돼",
    "복용해도돼",
    "금기",
    "처방",
    "성분",
    "DUR",
    "dur",
    "혈압약",
    "당뇨약",
    "혈당약",
    "타이레놀",
    "판콜",
    "아스피린",
    "노바스크",
    "메트포르민",
    "이지엔",
    "게보린",
    "탁센",
    "피임약",
    "감기약",
    "소화제",
    "진통제",
    "소염진통제",
    "항생제",
    "위장약",
    "스테로이드",
    "영양제",
    "비타민",
    "마그네슘",
    "오메가",
    "유산균",
)


def mentions_medication(text: str) -> bool:
    """문장이 (합성어가 아니라) 실제로 의약품을 언급하는지 판별한다."""
    return bool(STANDALONE_MEDICINE_WORD.search(text)) or any(k in text for k in MEDICATION_KEYWORDS)
