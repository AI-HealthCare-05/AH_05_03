def outlook_for(key: str, level: str) -> dict[str, Any] | None:
    """질환 하나의 전망. 카드를 받을 등급이 아니거나 사전에 없으면 `None`."""
    if level not in _LEVEL_RANK:
        return None
    entry = CATALOG.get(key)
    if entry is None:
        return None
    return {
        "key": key,
        "risk_level": level,
        "lead": _LEAD[level],
        "summary": entry.summary,
        "caveat": entry.caveat,
        "complications": [
            {
                "label": c.label,
                "organ": c.organ,
                "detail": c.detail,
                "effect": c.effect,
                "source": c.source,
                "causal": c.causal,
            }
            for c in entry.complications
        ],
        "monitoring": list(entry.monitoring),
    }


def outlooks_for(verdicts: list[Any]) -> list[dict[str, Any]]:
    """판정 목록에서 **기준을 넘었거나 경계에 있는 칸**만 골라 전망을 붙인다.

    급한 순으로 정렬한다. 같은 등급 안에서는 판정이 온 순서를 그대로 두는데, 그것이
    `SPECS` 순서(당뇨 → 고혈압 → 지질 → …)이고 바로 위 판정 축과 같은 차례로 읽히기
    때문이다. `list.sort` 가 안정 정렬이라 그 순서가 보존된다.

    **이름은 판정에서 가져온다.** 사전이 이름을 따로 들면 `SPECS` 와 두 벌이 되어
    한쪽만 고쳐진다 — `ckd` 가 "만성콩팥병"/"신기능 확인 필요" 로 갈렸던 것이 그
    꼴이었다(`assessment.SPECS` 주석).
    """
    found: list[dict[str, Any]] = []
    for verdict in verdicts:
        entry = outlook_for(verdict.key, verdict.risk_level)
        if entry is None:
            continue
        found.append({**entry, "name": verdict.name})
    found.sort(key=lambda e: _LEVEL_RANK[str(e["risk_level"])])
    return found
