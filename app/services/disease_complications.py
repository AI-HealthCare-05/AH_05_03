"""기준을 넘은 질환이 앞으로 무엇을 부르는가 — 합병증 전망.

이 저장소에는 앞날을 말하는 축이 이미 둘 있다. 둘 다 **아직 걸리지 않은 사람**에게
답한다.

* `disease_risk_matrix` — 수치 하나가 어떤 질환들을 가리키는가.
* `trajectory` — 지금이 유지되면 몇 년 뒤 기준을 넘고 있을 확률이 얼마인가.

**이미 넘은 사람에게는 둘 다 할 말이 없다.** 대사증후군 5/5 인 사람에게 "대사증후군이
될 확률" 을 띄우는 것은 정보가 아니고, 실제로 궤적은 그 칸을 지운다
(`assessment.present_targets`). 그래서 판정이 "매우 높음" 으로 나온 사람이 그다음에
읽을 것이 화면에 없었다 — 등급과 재측정 권고에서 끝났다.

이 모듈이 그 자리를 채운다. **이 질환을 그대로 두면 무엇이 뒤따르는가.**

지킨 것 셋
----------

**환자별 계산이 아니라 질환별 사전이다.** 합병증 목록은 사용자의 수치에서 나오지
않는다 — 수치가 정하는 것은 "어떤 질환이 걸렸나" 하나뿐이고, 그 질환에 무엇이 딸려
오는지는 지침과 코호트가 정한다. 그래서 이 표는 입력에 대해 상수다. 확률을 만들어
붙이지 않는 이유도 같다 — "당신은 5년 안에 망막병증이 생깁니다" 를 말할 근거가 이
서비스에 없다.

**연관과 인과를 여기서도 가른다.** `disease_risk_matrix.Evidence` 와 같은 규칙이다.
낮은 HDL 은 합병증 목록을 아예 갖지 않고, 요산과 만성염증은 인과가 아니라고 밝혀진
고리를 `causal=False` 로 적는다 — 중재시험이 실패한 고리를 "이것 때문에 저렇게 된다"
로 쓰면 안 된다.

**효과크기와 출처를 같이 적는다.** 크기 없는 합병증 목록은 겁주기이고, 출처 없는
크기는 검증할 수 없다. 숫자를 못 대는 고리는 지침 이름만 적고 크기를 말하지 않는다.

등급으로 가르는 것
------------------

`CAUTION` 이상만 카드를 받는다. `NORMAL` 에 합병증을 띄우면 기준 안에 있다는 답을
스스로 뒤집는 셈이고, `INSUFFICIENT_DATA` 는 아직 아무 답도 못 한 칸이다.
`CAUTION` 과 `HIGH` 이상은 첫 줄이 다르다 — 경계에 있는 것과 넘은 것은 다른 소식이다.
"""

