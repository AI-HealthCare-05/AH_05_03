def search_food_catalog(query: str, limit: int = 3) -> list[FoodNutritionItem]:
    """카탈로그에서 질의어와 가장 잘 맞는 음식을 검색한다."""
    clean_query = query.strip().replace(" ", "").lower()
    if not clean_query:
        return []

    # 1. 완전 일치 또는 시작 일치
    exact_matches: list[FoodNutritionItem] = []
    partial_matches: list[FoodNutritionItem] = []

    for item in STANDARD_FOOD_CATALOG:
        norm_name = item.food_name.replace(" ", "").lower()
        if clean_query == norm_name:
            exact_matches.append(item)
        elif clean_query in norm_name or norm_name in clean_query:
            partial_matches.append(item)

    results = exact_matches + [m for m in partial_matches if m not in exact_matches]
    return results[:limit]
